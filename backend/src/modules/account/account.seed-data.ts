import type { AccountCategoryValue, BalanceDirectionValue } from "./account.types.js";

export interface StandardAccountSeed {
  code: string;
  name: string;
  category: AccountCategoryValue;
  normalDirection: BalanceDirectionValue;
  parentCode?: string;
}

const debit = (code: string, name: string, category: AccountCategoryValue): StandardAccountSeed => ({
  code, name, category, normalDirection: "DEBIT",
});
const credit = (
  code: string,
  name: string,
  category: AccountCategoryValue,
  parentCode?: string,
): StandardAccountSeed => ({
  code,
  name,
  category,
  normalDirection: "CREDIT",
  ...(parentCode ? { parentCode } : {}),
});

